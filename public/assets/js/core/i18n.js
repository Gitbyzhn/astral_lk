const DICTS = { kk, ru };
const STORAGE_KEY = 'astral.lang';
const listeners = new Set();

function detect() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && saved in DICTS) return saved;
  } catch {
    /* сақтау орны жабық (мысалы, sandbox iframe) */
  }
  return 'kk';
}

let lang = detect();
document.documentElement.lang = lang;

export const getLang = () => lang;

export function setLang(next) {
  if (!(next in DICTS) || next === lang) return;
  lang = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    /* сақтау орны жабық */
  }
  document.documentElement.lang = next;
  for (const fn of listeners) fn(next);
}

/** Тіл ауысқанда шақырылады. Қайтарылған функция жазылымды тоқтатады. */
export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

function pluralRu(n, forms) {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return forms[2];
  if (b > 1 && b < 5) return forms[1];
  if (b === 1) return forms[0];
  return forms[2];
}

/**
 * @param {keyof typeof kk} key
 * @param {Record<string, string | number>} [vars] — {n} болса, көпше түр таңдалады
 */
export function t(key, vars) {
  let value = DICTS[lang][key] ?? kk[key] ?? key;
  if (Array.isArray(value) && typeof value[0] === 'string' && value.length === 3 && vars?.n !== undefined) {
    value = pluralRu(Number(vars.n), value);
  }
  if (typeof value !== 'string') return value;
  return vars ? value.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`).toString()) : value;
}

/** API қате кодын оқылатын мәтінге айналдырады. */
export function errorText(error) {
  if (!error) return t('error_generic');
  if (error.code === 'network') return t('error_network');
  const key = error.code;
  return key && key in kk ? t(key) : t('error_generic');
}
